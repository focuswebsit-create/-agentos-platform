#!/usr/bin/env bash
#
# Builds supabase/apply/01_bundle_development.sql from supabase/migrations/.
#
# Generated, never hand-edited, so it cannot drift from the migrations that the
# RLS suite verifies. CI-safe: it only reads the migrations and writes one file.
#
# The bundle is ONE transaction:
#   - a guard that REFUSES to run if AgentOS objects already exist, so it cannot
#     be applied twice or onto the wrong project by accident;
#   - every migration, in numeric order;
#   - a post-check that rolls the whole thing back if anything expected is
#     missing or if anon can execute any function.
# All or nothing: a failure part-way leaves the project exactly as it was.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=supabase/apply/01_bundle_development.sql
shopt -s nullglob
FILES=(supabase/migrations/[0-9]*.sql)
[ ${#FILES[@]} -gt 0 ] || { echo "no migrations found" >&2; exit 1; }

{
  cat <<'HEAD'
-- =============================================================================
-- 01_bundle_development.sql — GENERATED by scripts/build-apply-bundle.sh
-- DO NOT EDIT BY HAND. Regenerate it from supabase/migrations/.
--
-- FOR THE AgentOS-DEVELOPMENT PROJECT ONLY. Run 00_preflight.sql first and
-- confirm the project in the dashboard. Run 02_verify.sql afterwards.
--
-- One transaction. If any statement fails, NOTHING is applied.
-- =============================================================================

begin;

-- Refuse to run on a project that already has AgentOS installed. Applying twice
-- would fail part-way on "type already exists"; refusing up front is clearer
-- and guarantees the transaction never starts modifying anything.
do $$
begin
  if to_regclass('public.organizations') is not null
     or exists (select 1 from pg_type t join pg_namespace n on n.oid = t.typnamespace
                where n.nspname = 'public' and t.typname = 'org_role') then
    raise exception 'AgentOS is already installed in this database - refusing to apply the bundle';
  end if;
  if to_regclass('auth.users') is null then
    raise exception 'auth.users does not exist - this does not look like a Supabase project';
  end if;
end;
$$;

HEAD

  for f in "${FILES[@]}"; do
    printf '\n-- ===========================================================================\n'
    printf -- '-- >>> %s\n' "$(basename "$f")"
    printf -- '-- ===========================================================================\n\n'
    cat "$f"
    printf '\n'
  done

  cat <<'TAIL'

-- =============================================================================
-- Post-check, inside the transaction. Any failure here rolls back everything.
-- =============================================================================
do $$
declare
  v_missing text;
  v_open    text;
begin
  select string_agg(t, ', ') into v_missing
  from unnest(array[
    'organizations','memberships','profiles','invitations','platform_admins',
    'audit_events','agents','agent_versions','global_templates',
    'global_template_versions','template_installations','runs','run_steps',
    'usage_events','usage_reservations','usage_periods'
  ]) as t
  where to_regclass('public.' || t) is null;

  if v_missing is not null then
    raise exception 'post-check: missing tables: %', v_missing;
  end if;

  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                 where n.nspname = 'public' and p.proname = 'create_organization') then
    raise exception 'post-check: create_organization was not created';
  end if;

  select string_agg(p.proname, ', ') into v_open
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prorettype <> 'trigger'::regtype
    and has_function_privilege('anon', p.oid, 'EXECUTE');
  if v_open is not null then
    raise exception 'post-check: anon can execute: %', v_open;
  end if;
end;
$$;

commit;

-- Reaching this line means every migration applied and every check passed.
TAIL
} > "$OUT"

echo "wrote $OUT from ${#FILES[@]} migrations ($(wc -c < "$OUT") bytes)"
