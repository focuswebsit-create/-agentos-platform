#!/usr/bin/env bash
#
# Builds supabase/apply/03_incremental_0019_0022.sql: migrations 0019-0022 in
# ONE transaction, for a database that already has 0001-0018 (the
# AgentOS-Development project as of 2026-11-14).
#
# Guards at both ends, all fatal and all rolled back:
#   - refuses unless 0001-0018 are present (runs, settle_run, profiles backfill era);
#   - refuses if any of 0020-0022 is already applied;
#   - after applying, refuses to commit if an expected object is missing or if
#     anon can execute any public function.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="supabase/apply/03_incremental_0019_0022.sql"
MIGRATIONS=(
  supabase/migrations/0019_settle_run_idempotent.sql
  supabase/migrations/0020_billing_entitlements.sql
  supabase/migrations/0021_test_runs.sql
  supabase/migrations/0022_knowledge.sql
)

{
  cat <<'HEADER'
-- =============================================================================
-- AgentOS — incremental update 0019 → 0022, ONE transaction
--
-- GENERATED by scripts/build-incremental-bundle.sh. Do not edit by hand.
--
-- FOR: a database that already has migrations 0001–0018 (AgentOS-Development).
-- HOW: Supabase → SQL Editor → New query → paste this whole file → Run.
--
-- All or nothing: if any statement fails, everything rolls back and the
-- database is exactly as it was. It refuses to start if 0001–0018 are missing
-- or if 0020–0022 are already applied, so running it twice changes nothing.
--
-- DATA IT CHANGES: inserts the three plan rows (Starter/Business/Pro v1,
-- purchasable = false). Adds two columns to `runs` with defaults. No existing
-- row is updated or deleted. Existing organisations keep their current limits.
-- =============================================================================

begin;

-- ---- preflight -------------------------------------------------------------
do $$
begin
  if to_regclass('public.runs') is null
     or to_regprocedure('public.settle_run(uuid, public.run_status, bigint, jsonb, text)') is null
     or to_regclass('public.usage_reservations') is null then
    raise exception 'preflight: migrations 0001-0018 are not all present here - refusing. Use 01_bundle_development.sql on an empty database instead.';
  end if;
  if to_regclass('public.plans') is not null
     or to_regclass('public.knowledge_bases') is not null
     or to_regprocedure('public.start_test_run(uuid, jsonb)') is not null then
    raise exception 'preflight: 0020-0022 are already (partly) applied here - refusing. Nothing was changed.';
  end if;
end;
$$;

HEADER

  for f in "${MIGRATIONS[@]}"; do
    echo "-- >>> $(basename "$f")"
    cat "$f"
    echo
    echo "-- <<< $(basename "$f")"
    echo
  done

  cat <<'FOOTER'
-- ---- post-check ------------------------------------------------------------
do $$
declare
  v_missing text;
  v_open    text;
begin
  select string_agg(t, ', ') into v_missing
  from unnest(array[
    'public.plans', 'public.plan_versions', 'public.subscriptions',
    'public.subscription_events', 'public.billing_webhook_events',
    'public.entitlement_overrides', 'public.knowledge_bases',
    'public.knowledge_documents', 'public.knowledge_chunks'
  ]) as t
  where to_regclass(t) is null;
  if v_missing is not null then
    raise exception 'post-check: missing tables: %', v_missing;
  end if;

  if to_regprocedure('public.effective_entitlements(uuid)') is null
     or to_regprocedure('public.start_test_run(uuid, jsonb)') is null
     or to_regprocedure('public.add_knowledge_document(uuid, text, text, text, integer, bytea, text[])') is null then
    raise exception 'post-check: an expected function was not created';
  end if;

  if (select count(*) from public.plan_versions) <> 3 then
    raise exception 'post-check: expected exactly 3 plan versions';
  end if;

  select string_agg(p.oid::regprocedure::text, ', ') into v_open
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prorettype <> 'pg_catalog.trigger'::regtype
    and has_function_privilege('anon', p.oid, 'EXECUTE');
  if v_open is not null then
    raise exception 'post-check: anon can execute: %', v_open;
  end if;
end;
$$;

commit;
FOOTER
} > "$OUT"

echo "wrote $OUT"
