#!/usr/bin/env bash
#
# Builds supabase/apply/04_incremental_0023_0024.sql: migrations 0023-0024 in
# ONE transaction, for a database that already has 0001-0022 (the
# AgentOS-Development project as of 2026-11-15).
#
# Guards at both ends, all fatal and all rolled back:
#   - refuses unless 0001-0018 are present (runs, settle_run, profiles backfill era);
#   - refuses if any of 0020-0022 is already applied;
#   - after applying, refuses to commit if an expected object is missing or if
#     anon can execute any public function.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="supabase/apply/04_incremental_0023_0024.sql"
MIGRATIONS=(
  supabase/migrations/0023_settlement_period.sql
  supabase/migrations/0024_web_chat.sql
)

{
  cat <<'HEADER'
-- =============================================================================
-- AgentOS — incremental update 0023 → 0024, ONE transaction
--
-- GENERATED by scripts/build-incremental-0023-0024.sh. Do not edit by hand.
--
-- FOR: a database that already has migrations 0001–0022 (AgentOS-Development).
-- HOW: Supabase → SQL Editor → New query → paste this whole file → Run.
--
-- All or nothing: if any statement fails, everything rolls back and the
-- database is exactly as it was. It refuses to start if 0001–0022 are missing
-- or if 0024 is already applied, so running it twice changes nothing.
--
-- DATA IT CHANGES: none. 0023 replaces three settlement functions (same
-- signatures and grants); 0024 adds the Web Chat tables and functions.
-- =============================================================================

begin;

-- ---- preflight -------------------------------------------------------------
do $$
begin
  if to_regclass('public.knowledge_bases') is null
     or to_regclass('public.plans') is null
     or to_regprocedure('public.start_test_run(uuid, jsonb)') is null then
    raise exception 'preflight: migrations 0001-0022 are not all present here - refusing. Apply 03_incremental_0019_0022.sql first.';
  end if;
  if to_regclass('public.chat_widgets') is not null then
    raise exception 'preflight: 0024 is already applied here - refusing. Nothing was changed.';
  end if;
end;
$$;

HEADER

  for f in "${MIGRATIONS[@]}"; do
    echo "-- >>> $(basename "$f")"
    cat "$f"
    echo
    echo "-- <<< $(basename "$f")"
    echo
  done

  cat <<'FOOTER'
-- ---- post-check ------------------------------------------------------------
do $$
declare
  v_missing text;
  v_open    text;
begin
  select string_agg(t, ', ') into v_missing
  from unnest(array['public.chat_widgets', 'public.conversations', 'public.conversation_messages']) as t
  where to_regclass(t) is null;
  if v_missing is not null then
    raise exception 'post-check: missing tables: %', v_missing;
  end if;

  if to_regprocedure('public.run_usage_period(uuid)') is null
     or to_regprocedure('public.post_visitor_message(text, bytea, text, jsonb)') is null
     or to_regprocedure('public.open_conversation(text, bytea, bytea)') is null then
    raise exception 'post-check: an expected function was not created';
  end if;

  select string_agg(p.oid::regprocedure::text, ', ') into v_open
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prorettype <> 'pg_catalog.trigger'::regtype
    and has_function_privilege('anon', p.oid, 'EXECUTE');
  if v_open is not null then
    raise exception 'post-check: anon can execute: %', v_open;
  end if;
end;
$$;

commit;
FOOTER
} > "$OUT"

echo "wrote $OUT"
